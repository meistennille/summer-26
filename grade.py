#to know my grade based on my score
score = int(input("Score: "))

if score >= 90:
    print("Your grade is A. Excellent!")
elif score >= 80:
    print ("Your grade is B. Very good!")
elif score >= 70:
    print ("Your grade is C. Good!")
elif score >= 60:
    print ("Your grade is D. Fair.")
else:
    print ("Your grade is F. Re-take course.")
